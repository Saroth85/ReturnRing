#!/usr/bin/env node
// Generates src/api/types.gen.ts from the API JSON Schemas (contracts/json/api/*.schema.json,
// exported from apps/api/schemas.py, ADR-15). Generated, never edited.
//
//   node scripts/gen-types.mjs           write the file
//   node scripts/gen-types.mjs --check   exit 1 when the committed file is stale
//
// The schemas share their $defs (Metric, Provenance, Lever, ...). They are merged into one schema
// so every type is declared once; the merge fails if two files define the same name differently.
// Before compiling, the script removes what TypeScript cannot express and what would only add
// noise:
// - if/then/else rules (the JSON Schema checks a reason for override, the lever value per id):
//   the API enforces them, and json-schema-to-typescript would turn them into index signatures;
// - contains/minContains/maxContains (at most one lever per id): same reason, every lever array
//   would become `{[k: string]: unknown} & ...` and a typed lever list would no longer fit;
// - property titles that pydantic adds ("Return Id"), which would become one alias per field.
// minItems/maxItems are ignored (ignoreMinAndMaxItems): arrays are plain `T[]`, not tuple unions,
// so code must handle the empty case itself; the API still enforces the bounds.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// Pinned contract (contract-pin/README.md) until the UI migrates to the API's current contract.
const CONTRACTS = path.resolve(process.env.RETURNRING_CONTRACTS_DIR || path.resolve(ROOT, 'contract-pin'));
const SCHEMA_DIR = path.join(CONTRACTS, 'json/api');
const OUT = path.join(ROOT, 'src/api/types.gen.ts');
const check = process.argv.includes('--check');

const BANNER = `/* eslint-disable */
// Generated by scripts/gen-types.mjs from contracts/json/api/*.schema.json (ADR-15).
// Do not edit: run \`npm run gen:types\`. Components import src/api/models.ts, not this file.`;

function stableStringify(value) {
  if (Array.isArray(value)) return `[${value.map(stableStringify).join(',')}]`;
  if (value && typeof value === 'object') {
    return `{${Object.keys(value)
      .sort()
      .map((k) => `${JSON.stringify(k)}:${stableStringify(value[k])}`)
      .join(',')}}`;
  }
  return JSON.stringify(value);
}

/** Keywords TypeScript cannot express; the API enforces them at runtime. */
const DROPPED_KEYWORDS = new Set(['if', 'then', 'else', 'contains', 'minContains', 'maxContains', '$comment', '$schema']);

/** Removes conditional rules and property-level titles, and points $refs at "definitions". */
function clean(node, isDefinitionRoot = false) {
  if (Array.isArray(node)) return node.map((item) => clean(item));
  if (!node || typeof node !== 'object') return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (DROPPED_KEYWORDS.has(key)) continue;
    if (key === 'title' && !isDefinitionRoot) continue;
    if (key === '$ref' && typeof value === 'string') {
      out.$ref = value.replace('#/$defs/', '#/definitions/');
      continue;
    }
    if (key === 'properties' && value && typeof value === 'object') {
      out.properties = Object.fromEntries(Object.entries(value).map(([name, schema]) => [name, clean(schema)]));
      continue;
    }
    out[key] = clean(value);
  }
  if (Array.isArray(out.allOf)) {
    out.allOf = out.allOf.filter((part) => part && Object.keys(part).length > 0);
    if (out.allOf.length === 0) delete out.allOf;
  }
  return out;
}

export function loadSchemas() {
  const files = readdirSync(SCHEMA_DIR)
    .filter((f) => f.endsWith('.schema.json'))
    .sort();
  if (files.length === 0) throw new Error(`no schema in ${SCHEMA_DIR}`);
  const definitions = new Map(); // name -> {schema, from}
  const models = []; // {stem, title}
  const add = (name, schema, from) => {
    const existing = definitions.get(name);
    if (existing && stableStringify(existing.schema) !== stableStringify(schema)) {
      throw new Error(`definition ${name} differs between ${existing.from} and ${from}`);
    }
    if (!existing) definitions.set(name, { schema, from });
  };
  for (const file of files) {
    const stem = file.slice(0, -'.schema.json'.length);
    const schema = JSON.parse(readFileSync(path.join(SCHEMA_DIR, file), 'utf8'));
    const { $defs = {}, $schema: _dialect, $comment: _comment, ...top } = schema;
    if (typeof top.title !== 'string') throw new Error(`${file} has no title`);
    for (const [name, def] of Object.entries($defs)) add(name, def, file);
    add(top.title, top, file);
    models.push({ stem, title: top.title });
  }
  return { files, definitions, models };
}

async function generate() {
  const { definitions, models } = loadSchemas();
  const names = [...definitions.keys()].sort();
  const combined = {
    title: 'ApiSchemas',
    description:
      'Every API model by its schema file name (contracts/json/api/<name>.schema.json); endpoints.json names them this way.',
    type: 'object',
    additionalProperties: false,
    required: models.map((m) => m.stem),
    properties: Object.fromEntries(models.map((m) => [m.stem, { $ref: `#/definitions/${m.title}` }])),
    definitions: Object.fromEntries(names.map((name) => [name, clean(definitions.get(name).schema, true)])),
  };
  const ts = await compile(combined, 'ApiSchemas', {
    bannerComment: BANNER,
    additionalProperties: false,
    declareExternallyReferenced: true,
    unreachableDefinitions: true,
    strictIndexSignatures: true,
    enableConstEnums: false,
    ignoreMinAndMaxItems: true,
    format: true,
    style: { singleQuote: true, printWidth: 110, trailingComma: 'all' },
    cwd: SCHEMA_DIR,
  });
  return ts;
}

const output = await generate();
if (check) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    // missing file: stale
  }
  if (current !== output) {
    console.error('src/api/types.gen.ts is stale: run `npm run gen:types` and commit the result');
    process.exit(1);
  }
  console.log('types.gen.ts is up to date');
} else {
  writeFileSync(OUT, output);
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}
