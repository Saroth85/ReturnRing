"""Export the HTTP API contract of apps/api/schemas.py to contracts/json/api/ (ADR-15).

Writes one JSON Schema per model of API_MODELS (<name>.schema.json), endpoints.json (the endpoint
table) and openapi.json (built from a stub FastAPI app with the same models and routes).
Request and query models are exported in validation mode, responses in serialization mode.

    python -m scripts.export_api_schemas           # write
    python -m scripts.export_api_schemas --check   # exit 1 if a committed file differs
"""

from __future__ import annotations

import argparse
import inspect
import json
import re
import sys
from collections.abc import Callable, Sequence
from pathlib import Path
from typing import Annotated, Any, Literal

from fastapi import Body, FastAPI, Query
from fastapi import Path as PathParam

from apps.api.schemas import (
    API_CONTRACT_VERSION,
    API_MODELS,
    CSV,
    ENDPOINTS,
    JSON,
    MODE_HEADER,
    REQUEST_ID_HEADER,
    RETRY_AFTER_DOC,
    RETRY_AFTER_HEADER,
    RETRY_AFTER_OPENAPI,
    SSE,
    Endpoint,
    ErrorResponse,
)

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "contracts" / "json" / "api"
SCHEMA_DIALECT = "https://json-schema.org/draft/2020-12/schema"
GENERATED = "Generated by scripts/export_api_schemas.py from apps/api/schemas.py: do not edit"
INPUT_MODELS = frozenset(
    name for ep in ENDPOINTS for name in (ep.request, ep.query) if name is not None
)


def schema_for(name: str) -> dict[str, Any]:
    mode: Literal["validation", "serialization"] = (
        "validation" if name in INPUT_MODELS else "serialization"
    )
    schema = API_MODELS[name].model_json_schema(mode=mode)
    return {"$schema": SCHEMA_DIALECT, "$comment": GENERATED, **schema}


def endpoints_document() -> dict[str, Any]:
    return {
        "$comment": GENERATED,
        "contract_version": API_CONTRACT_VERSION,
        "headers": {
            MODE_HEADER: "on every response: live or cached (US-901)",
            REQUEST_ID_HEADER: "on every response; also stored in the audit log (NFR-12)",
            RETRY_AFTER_HEADER: RETRY_AFTER_DOC,
        },
        "error_body": "error",
        "endpoints": [ep.as_dict() for ep in ENDPOINTS],
    }


def _stub(ep: Endpoint) -> Callable[..., Any]:
    """A route function with the endpoint's parameters, for OpenAPI generation only."""
    params = [
        inspect.Parameter(
            name, inspect.Parameter.KEYWORD_ONLY, annotation=Annotated[str, PathParam()]
        )
        for name in re.findall(r"{(\w+)}", ep.path)
    ]
    if ep.query is not None:
        query_model = API_MODELS[ep.query]
        params.append(
            inspect.Parameter(
                "query", inspect.Parameter.KEYWORD_ONLY, annotation=Annotated[query_model, Query()]
            )
        )
    if ep.request is not None:
        body_model = API_MODELS[ep.request]
        params.append(
            inspect.Parameter(
                "body", inspect.Parameter.KEYWORD_ONLY, annotation=Annotated[body_model, Body()]
            )
        )

    def route(**_: Any) -> Any:
        raise NotImplementedError("contract stub: implemented in apps/api (phase 4)")

    route.__signature__ = inspect.Signature(params)  # type: ignore[attr-defined]
    route.__name__ = re.sub(r"\W+", "_", f"{ep.method.lower()}_{ep.path}").strip("_")
    route.__doc__ = f"{ep.summary}. Stories: {', '.join(ep.stories)}."
    return route


def contract_app() -> FastAPI:
    app = FastAPI(
        title="ReturnRing API",
        version=API_CONTRACT_VERSION,
        description=(
            "Contract of the ReturnRing API (ADR-15). Every response carries the headers "
            f"{MODE_HEADER} (live or cached) and {REQUEST_ID_HEADER}."
        ),
    )
    for ep in ENDPOINTS:
        responses: dict[int | str, dict[str, Any]] = {
            code: {"model": ErrorResponse} for code in (*ep.errors, 422)
        }
        if 429 in responses:
            responses[429]["headers"] = RETRY_AFTER_OPENAPI
        response_model: Any = API_MODELS[ep.response]
        if ep.media_type == SSE:
            responses[ep.status] = {
                "description": "Server-sent events; each data line is one event of "
                "agent_stream.schema.json",
                "content": {SSE: {"schema": {"type": "string"}}},
            }
            response_model = None
        elif CSV in ep.alt_media_types:
            responses[ep.status] = {"content": {CSV: {"schema": {"type": "string"}}}}
        app.add_api_route(
            ep.path,
            _stub(ep),
            methods=[ep.method],
            status_code=ep.status,
            response_model=response_model,
            responses=responses,
            summary=ep.summary,
            tags=[ep.path.split("/")[2] if ep.path.startswith("/api/") else "health"],
        )
    return app


def _dump(doc: Any) -> str:
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def render() -> dict[str, str]:
    """Every file of contracts/json/api/, by file name."""
    files = {f"{name}.schema.json": _dump(schema_for(name)) for name in API_MODELS}
    files["endpoints.json"] = _dump(endpoints_document())
    assert JSON == "application/json"
    files["openapi.json"] = _dump(contract_app().openapi())
    return files


def write(out: Path = OUT) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    files = render()
    for stale in out.glob("*.json"):
        if stale.name not in files:
            stale.unlink()
    written = []
    for name, text in files.items():
        path = out / name
        path.write_text(text, encoding="utf-8")
        written.append(path)
    return written


def check(out: Path = OUT) -> list[str]:
    """File names that are missing, stale or different from a fresh export."""
    files = render()
    found = {p.name for p in out.glob("*.json")} if out.exists() else set()
    problems = [f"stale: {name}" for name in sorted(found - set(files))]
    for name, text in files.items():
        path = out / name
        if not path.exists():
            problems.append(f"missing: {name}")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"differs: {name}")
    return problems


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="fail if files are out of date")
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args(argv)
    if args.check:
        problems = check(args.out)
        for problem in problems:
            print(problem, file=sys.stderr)
        if problems:
            print("run: python -m scripts.export_api_schemas", file=sys.stderr)
        return 1 if problems else 0
    for path in write(args.out):
        print(path.relative_to(ROOT) if path.is_relative_to(ROOT) else path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
